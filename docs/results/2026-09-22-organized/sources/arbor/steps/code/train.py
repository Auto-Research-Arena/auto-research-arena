DATA_BUDGET_TOKENS = 631_241_817

# ---------------------------------------------------------------------------
# Setup: tokenizer, model, optimizer, dataloader
# ---------------------------------------------------------------------------

# Axis H only: set a positive target to stop at the first probe below it, or 0.0 for
# probe-only calibration, which records the quality-versus-time curve and never stops.
TARGET_VAL_BPB = float(os.environ.get("AUTORESEARCH_TARGET_VAL_BPB", "0") or 0)
PROBE_ONLY = os.environ.get("AUTORESEARCH_PROBE_CURVE", "") == "1"
MEASURE_ONLY_STEPS = int(os.environ.get("AUTORESEARCH_MEASURE_ONLY_STEPS", "0") or 0)

t_start = time.time()
torch.manual_seed(42)
torch.cuda.manual_seed(42)
torch.set_float32_matmul_precision("high")
device = torch.device("cuda")
autocast_ctx = torch.amp.autocast(device_type="cuda", dtype=torch.bfloat16)
H100_BF16_PEAK_FLOPS = 989.5e12

tokenizer = Tokenizer.from_directory()
vocab_size = tokenizer.get_vocab_size()
print(f"Vocab size: {vocab_size:,}")

def build_model_config(depth):
    base_dim = depth * ASPECT_RATIO
    model_dim = ((base_dim + HEAD_DIM - 1) // HEAD_DIM) * HEAD_DIM
    num_heads = model_dim // HEAD_DIM
    return GPTConfig(
        sequence_len=MAX_SEQ_LEN, vocab_size=vocab_size,
        n_layer=depth, n_head=num_heads, n_kv_head=num_heads, n_embd=model_dim,
        window_pattern=WINDOW_PATTERN,
    )

config = build_model_config(DEPTH)
print(f"Model config: {asdict(config)}")

with torch.device("meta"):
    model = GPT(config)
model.to_empty(device=device)
model.init_weights()

param_counts = count_params(model)
print("Parameter counts:")
for key, value in param_counts.items():
    print(f"  {key:24s}: {value:,}")
num_params = param_counts['total']
num_flops_per_token = model.estimate_flops()
print(f"Estimated FLOPs per token: {num_flops_per_token:e}")

tokens_per_fwdbwd = DEVICE_BATCH_SIZE * MAX_SEQ_LEN

optimizer = model.setup_optimizer(
    unembedding_lr=UNEMBEDDING_LR,
    embedding_lr=EMBEDDING_LR,
    scalar_lr=SCALAR_LR,
    adam_betas=ADAM_BETAS,
    matrix_lr=MATRIX_LR,
    weight_decay=WEIGHT_DECAY,
)

model = torch.compile(model, dynamic=False)
# One static graph per curriculum context length (plus the eval graph): give dynamo room so a
# shape switch never trips the recompile limit into a slower dynamic graph.
import torch._dynamo
torch._dynamo.config.cache_size_limit = 32
torch._dynamo.config.accumulated_cache_size_limit = 256

train_loader = make_dataloader(tokenizer, DEVICE_BATCH_SIZE, MAX_SEQ_LEN, "train",
                              data_budget_tokens=DATA_BUDGET_TOKENS)
print(f"Data budget:    {DATA_BUDGET_TOKENS:,} distinct tokens from the shuffled pool")
harness = (TimeToTargetHarness(TARGET_VAL_BPB)
           if (TARGET_VAL_BPB > 0 or PROBE_ONLY) else None)
x, y, epoch = next(train_loader)  # prefetch first batch
# The first actual training microbatch is the curriculum's first context length: the same
# token positions, viewed as (rows, seq_len). Reshape here so the probe below sees exactly the
# microbatch the loop is about to train on, in the real training configuration.
x = x.view(tokens_per_fwdbwd // SEQ_WARMUP_ORDER[0], SEQ_WARMUP_ORDER[0])
y = y.view(tokens_per_fwdbwd // SEQ_WARMUP_ORDER[0], SEQ_WARMUP_ORDER[0])
# Dispatch-level FLOPs, measured HERE while memory still holds only the model and the
# optimizer state. Counted on the uncompiled module by the frozen probe.
from prepare import measure_flops_dispatch
flops_per_token_measured = measure_flops_dispatch(model, x, y)
print(f"FLOPs per token (measured at dispatch): {flops_per_token_measured:,}")

print(f"Time budget: {TIME_BUDGET}s")
print(f"Gradient accumulation ramp (progress < p -> accum): {BATCH_RAMP}")
print(f"Tokens per microbatch: {tokens_per_fwdbwd:,}; base accum {BATCH_RAMP_BASE_ACCUM} "
      f"= {BATCH_RAMP_BASE_ACCUM * tokens_per_fwdbwd:,} tokens/update")
print(f"Sequence-length curriculum (tokens < t -> seq_len): {SEQ_CURRICULUM} then {MAX_SEQ_LEN}; "
      f"shape-warmup order {SEQ_WARMUP_ORDER}; schedule token reference {SCHEDULE_TOKEN_REFERENCE:,}")

# Schedules (progress = max(training_time / TIME_BUDGET, tokens / SCHEDULE_TOKEN_REFERENCE))

def get_grad_accum(progress):
    for p_end, accum in BATCH_RAMP:
        if progress < p_end:
            return accum
    return BATCH_RAMP[-1][1]

def get_seq_len(tokens):
    for tokens_before, seq_len in SEQ_CURRICULUM:
        if tokens < tokens_before:
            return seq_len
    return MAX_SEQ_LEN

def get_progress(training_time, tokens):
    # Schedules advance with whichever is further along: the clock or the token stream.
    return min(max(training_time / TIME_BUDGET, tokens / SCHEDULE_TOKEN_REFERENCE), 1.0)

def get_batch_lr_scale(accum):
    # conditioning tracks the batch: LR ~ sqrt(tokens per update)
    return (accum / BATCH_RAMP_BASE_ACCUM) ** 0.5

def get_lr_multiplier(progress):
    if progress < WARMUP_RATIO:
        return progress / WARMUP_RATIO if WARMUP_RATIO > 0 else 1.0
    elif progress < 1.0 - WARMDOWN_RATIO:
        return 1.0
    else:
        cooldown = (1.0 - progress) / WARMDOWN_RATIO
        return cooldown * 1.0 + (1 - cooldown) * FINAL_LR_FRAC

def get_muon_momentum(tokens):
    frac = min(tokens / 157_286_400, 1)  # token-space warmup horizon, ramp-invariant
    return (1 - frac) * 0.85 + frac * 0.95

def get_weight_decay(progress):
    return WEIGHT_DECAY * (1 - progress)

# ---------------------------------------------------------------------------
# Training loop
# ---------------------------------------------------------------------------

t_start_training = time.time()
smooth_train_loss = 0
total_training_time = 0
tokens_consumed = 0
step = 0
phase_stats = {}   # seq_len -> [tokens, seconds, updates] over counted updates only
stage_stats = {}   # accum -> [tokens, seconds, updates] over counted updates only

while True:
    # This update's granularity comes from the training clock, before any of its work:
    # accum microbatches -> this update's OWN true token count.
    progress = get_progress(total_training_time, tokens_consumed)
    grad_accum_steps = get_grad_accum(progress)
    tokens_this_update = grad_accum_steps * tokens_per_fwdbwd
    # Context length for this update's microbatches. The token count per microbatch is
    # identical to the loader's block (rows * seq_len == DEVICE_BATCH_SIZE * MAX_SEQ_LEN),
    # so tokens_this_update is unchanged by the curriculum.
    seq_len = (SEQ_WARMUP_ORDER[step] if step < len(SEQ_WARMUP_ORDER)
               else get_seq_len(tokens_consumed))
    rows = tokens_per_fwdbwd // seq_len

    torch.cuda.synchronize()
    t0 = time.time()
    for micro_step in range(grad_accum_steps):
        with autocast_ctx:
            loss = model(x.view(rows, seq_len), y.view(rows, seq_len))
        train_loss = loss.detach()
        loss = loss / grad_accum_steps
        loss.backward()
        x, y, epoch = next(train_loader)

    # Schedules
    lrm = get_lr_multiplier(progress)
    batch_lr_scale = get_batch_lr_scale(grad_accum_steps)
    muon_momentum = get_muon_momentum(tokens_consumed)
    muon_weight_decay = get_weight_decay(progress)
    for group in optimizer.param_groups:
        group["lr"] = group["initial_lr"] * lrm * batch_lr_scale
        if group['kind'] == 'muon':
            group["momentum"] = muon_momentum
            group["weight_decay"] = muon_weight_decay
    optimizer.step()
    model.zero_grad(set_to_none=True)

    train_loss_f = train_loss.item()

    # Fast fail: abort if loss is exploding or NaN
    if math.isnan(train_loss_f) or train_loss_f > 100:
        print("FAIL")
        exit(1)

    torch.cuda.synchronize()
    t1 = time.time()
    dt = t1 - t0

    if step > 10:
        total_training_time += dt
        entry = phase_stats.setdefault(seq_len, [0, 0.0, 0])
        entry[0] += tokens_this_update
        entry[1] += dt
        entry[2] += 1
        s_entry = stage_stats.setdefault(grad_accum_steps, [0, 0.0, 0, total_training_time - dt])
        s_entry[0] += tokens_this_update
        s_entry[1] += dt
        s_entry[2] += 1

    # Logging
    ema_beta = 0.9
    smooth_train_loss = ema_beta * smooth_train_loss + (1 - ema_beta) * train_loss_f
    debiased_smooth_loss = smooth_train_loss / (1 - ema_beta**(step + 1))
    pct_done = 100 * progress
    tok_per_sec = int(tokens_this_update / dt)
    mfu = 100 * num_flops_per_token * tokens_this_update / dt / H100_BF16_PEAK_FLOPS
    remaining = max(0, TIME_BUDGET - total_training_time)

    print(f"\rstep {step:05d} ({pct_done:.1f}%) | loss: {debiased_smooth_loss:.6f} | accum: {grad_accum_steps} | ctx: {rows}x{seq_len} | tok/update: {tokens_this_update:,} | lrm: {lrm:.2f} | bscale: {batch_lr_scale:.2f} | dt: {dt*1000:.0f}ms | tok/sec: {tok_per_sec:,} | mfu: {mfu:.1f}% | epoch: {epoch} | remaining: {remaining:.0f}s    ", end="", flush=True)

    # GC management (Python's GC causes ~500ms stalls)
    if step == 0:
        gc.collect()
        gc.freeze()
        gc.disable()
    elif (step + 1) % 5000 == 0:
        gc.collect()

    step += 1
    tokens_consumed += tokens_this_update

    # Axis H: the frozen harness owns the clock, the probe cadence and the crossing.
    if harness is not None and harness.tick(model, tokenizer, dt, tokens_this_update):
        break

    if MEASURE_ONLY_STEPS and step >= MEASURE_ONLY_STEPS:
        break

    # Time's up — but only stop after warmup steps so we don't count compilation
    if step > 10 and total_training_time >= TIME_BUDGET:
        break

print()  # newline after \r training log

for seq_len_key in sorted(phase_stats):
    tok, secs, upd = phase_stats[seq_len_key]
    print(f"[phase] ctx={seq_len_key:5d} updates={upd:4d} "
          f"tokens={tok:,} seconds={secs:7.1f} tok/s={int(tok / secs) if secs > 0 else 0:,}")

for accum_key in sorted(stage_stats):
    tok, secs, upd, t_begin = stage_stats[accum_key]
    print(f"[stage] accum={accum_key:3d} updates={upd:4d} tokens={tok:,} "
          f"seconds={secs:7.1f} clock_start={t_begin:6.1f}s clock_end={t_begin + secs:6.1f}s "
          f"tok/update={tok // max(upd, 1):,}")

total_tokens = tokens_consumed
t_end = time.time()

# Every score comes from the FROZEN prepare.py. train.py may change the model; it may
# not compute the number the model is judged on.
report_efficiency_metrics(
    model, tokenizer,
    num_steps=step,
    tokens_per_step=tokens_consumed // max(step, 1),
    total_tokens=tokens_consumed,
    training_seconds=total_training_time,
    total_seconds=t_end - t_start,
    final_epoch=epoch,
    flops_measured=flops_per_token_measured,
    harness=harness,
)
print(f"depth:            {DEPTH}")
