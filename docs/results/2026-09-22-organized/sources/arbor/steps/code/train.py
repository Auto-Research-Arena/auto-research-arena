# Optimization
# Tokens-per-update is a SCHEDULE, not a constant: the number of grad-accum microbatches
# per logical update grows in stages with the training-clock progress. Reference accum
# (BATCH_RAMP_BASE_ACCUM) is the 1x reference update (2 x 128 x 2048 = 2^19 tokens); LRs
# below are the 1x-tuned values and get multiplied by sqrt(accum / base_accum) each update.
# Terminal-only coarsening: every boundary and every per-stage value through the mid phase is
# exactly the merged trunk's; only the FINAL stage (progress >= 0.84, the last ~15% of the
# token-keyed progress) is raised from accum 10 to 14 (3.67M tokens/update). Critical batch
# size grows as loss falls, so this is the one part of the ramp that prior diagnostics found
# free; mid-phase boundaries are deliberately left untouched because that is where advancing
# the ramp cost quality.
BATCH_RAMP = [(0.11, 2), (0.26, 3), (0.46, 4), (0.66, 6), (0.84, 8), (1.01, 14)]
BATCH_RAMP_BASE_ACCUM = 2

# Sequence-length curriculum. The loader hands out a fixed DEVICE_BATCH_SIZE x MAX_SEQ_LEN
# block of the token stream; that block is RESHAPED into (rows, seq_len) views with the same
# number of token positions, so early updates see the same tokens at shorter context. Shorter
# context costs strictly less attention (all windows collapse to min(window, seq_len)) and
# less activation traffic, so tokens/second rises at equal token count. Keyed on tokens
# consumed, not on the clock, so the curriculum is throughput-invariant.
SEQ_CURRICULUM = [(45_000_000, 512), (120_000_000, 1024)]  # (tokens_before, seq_len); native after
# Every curriculum shape is a separate torch.compile graph (dynamic=False). Compile them in
# the first updates, whose duration the reference clock excludes, so no shape switch later in
# the run pays for compilation on the counted clock. These are real training updates on real
# counted tokens; only their order of context length is forced.
SEQ_WARMUP_ORDER = [512, 1024, 2048]
# Reference token throughput x TIME_BUDGET (645k tok/s x 600s, rounded up for margin): the
# token count at which the schedules (batch ramp, LR anneal) consider the run "done". Progress
# is max(clock, tokens) so a run that is faster than the reference advances its schedules in
# token space -- keeping the trunk's per-token trajectory and converting the throughput gain
# into an earlier crossing instead of into more fine-grained updates -- while a slower run
# still completes its terminal anneal by TIME_BUDGET.
SCHEDULE_TOKEN_REFERENCE = 400_000_000
EMBEDDING_LR = 0.8      # learning rate for token embeddings (Adam), at base accum
UNEMBEDDING_LR = 0.005  # learning rate for lm_head (Adam), at base accum
MATRIX_LR = 0.055       # learning rate for matrix parameters (Muon), at base accum
SCALAR_LR = 0.5         # learning rate for per-layer scalars (Adam), at base accum
WEIGHT_DECAY = 0.2      # cautious weight decay for Muon
ADAM_BETAS = (0.8, 0.95) # Adam beta1, beta2
WARMUP_RATIO = 0.0      # fraction of time budget for LR warmup
WARMDOWN_RATIO = 1.0    # full-length triangular decay: LR falls linearly from 1.0 at t=0 to FINAL_LR_FRAC at t=TIME_BUDGET
FINAL_LR_FRAC = 0.0     # final LR as fraction of initial

# Model size
DEPTH = 8               # number of transformer layers
